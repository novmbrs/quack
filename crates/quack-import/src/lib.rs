use std::path::PathBuf;

use quack_core::ids::GuildId;
use quack_db::import::{self, ImportMode};
use quack_db::{Db, Fence};
use tracing::Instrument as _;

pub use error::ImportError;
pub use report::{GuildOutcome, Report};

/// Bumped whenever a mapping changes; part of the fingerprint (§19.11).
pub const TRANSFORM_VERSION: i32 = 1;

/// What `quack import-mysql` was asked to do.
#[derive(Clone)]
pub struct ImportOptions {
    /// The Go database (`QUACK_IMPORT_SOURCE_URL`). Secret: never logged.
    pub source_url: String,
    /// Check everything and keep nothing but the `import_runs` row.
    pub dry_run: bool,
    /// Also write the JSON report here.
    pub report_path: Option<PathBuf>,
}

impl std::fmt::Debug for ImportOptions {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("ImportOptions")
            .field("source_url", &"[secret]")
            .field("dry_run", &self.dry_run)
            .field("report_path", &self.report_path)
            .finish()
    }
}

/// Imports the MySQL source into `db` (§19). Returns the report; the run
/// succeeded when [`Report::ok`] is true (`quack import-mysql` exits 0 then,
/// 1 otherwise). An `Err` means nothing was imported: the source shape is
/// unknown, another process holds the fence, a server was imported from
/// different data, or a database is unreachable.
pub async fn run(db: &Db, options: &ImportOptions) -> Result<Report, ImportError> {
    let span = tracing::info_span!("import mysql", import.dry_run = options.dry_run);
    async {
        let fence = Fence::try_acquire(db.connect_options())
            .await?
            .ok_or(ImportError::Fenced)?;
        let result = run_fenced(db, options).await;
        fence.release().await?;
        let report = result?;
        if let Some(path) = &options.report_path {
            std::fs::write(path, report.to_json())?;
        }
        tracing::info!(import.ok = report.ok, "import finished");
        Ok(report)
    }
    .instrument(span)
    .await
}

async fn run_fenced(db: &Db, options: &ImportOptions) -> Result<Report, ImportError> {
    let mut src = source::Source::open(&options.source_url).await?;
    let (snapshot_at, server_version) = src.clock().await?;
    let evaluated_at = snapshot_at;
    let mut report = Report {
        mode: if options.dry_run { "dry_run" } else { "apply" }.to_owned(),
        transform_version: TRANSFORM_VERSION,
        ..Report::default()
    };
    let tables = source::digest::tables(&mut src).await?;
    let fingerprint = source::digest::fingerprint(&src.shape.ledger_rows, &tables);
    report.source = report::SourceSection {
        server_version,
        ledger: src.shape.ledger_rows.clone(),
        snapshot_at: Some(snapshot_at),
        evaluated_at: Some(evaluated_at),
        tables,
        fingerprint: fingerprint.clone(),
        shape: src.shape.features(),
        manifest: src.shape.manifest(),
    };
    let guilds = tables::guilds::list(&mut src, &mut report).await?;
    // Refuse before writing anything if a server came from other data.
    let mut done = Vec::new();
    {
        let mut conn = db.conn().await?;
        for g in &guilds {
            let id =
                GuildId::try_from(g.id).map_err(|_| ImportError::server("invalid server ID"))?;
            match import::imported_from(&mut conn, id).await? {
                Some(existing) if existing != fingerprint => {
                    return Err(ImportError::ChangedSource {
                        guild: g.id,
                        existing,
                    });
                }
                Some(_) => done.push(g.id),
                None => {}
            }
        }
    }
    let mode = if options.dry_run {
        ImportMode::DryRun
    } else {
        ImportMode::Apply
    };
    let run_id = {
        let mut conn = db.conn().await?;
        import::start_run(
            &mut conn,
            mode,
            &fingerprint,
            TRANSFORM_VERSION,
            evaluated_at,
        )
        .await?
    };
    report.run_id = Some(run_id.to_string());
    tables::counted::run(&mut src, &mut report).await?;
    if let Err(e) =
        tables::guilds::import_accounts(db, &mut src, &mut report, !options.dry_run).await
    {
        report.problem("global", e.to_string());
    }
    servers(
        db,
        &mut src,
        &mut report,
        guilds,
        &done,
        run_id,
        &fingerprint,
        options.dry_run,
        evaluated_at,
    )
    .await;
    report.finish();
    let json =
        serde_json::to_value(&report).map_err(|e| ImportError::Report(std::io::Error::other(e)))?;
    {
        let mut conn = db.conn().await?;
        import::finish_run(&mut conn, run_id, &json).await?;
    }
    src.close().await?;
    Ok(report)
}

/// Imports each server in turn; one server's failure is recorded and the
/// next one still runs.
#[expect(
    clippy::too_many_arguments,
    reason = "the run's fixed facts, passed once"
)]
async fn servers(
    db: &Db,
    src: &mut source::Source,
    report: &mut Report,
    guilds: Vec<guild::GuildKey>,
    done: &[i64],
    run_id: uuid::Uuid,
    fingerprint: &str,
    dry_run: bool,
    evaluated_at: time::OffsetDateTime,
) {
    let finish = if dry_run {
        guild::Finish::Rollback
    } else {
        guild::Finish::Commit
    };
    for g in guilds {
        let name = g.id.to_string();
        if done.contains(&g.id) {
            report.guilds.insert(name, GuildOutcome::AlreadyImported);
            continue;
        }
        match guild::import(db, src, g, run_id, fingerprint, evaluated_at, finish).await {
            Ok(fragment) => {
                report.merge(&name, fragment);
                let outcome = if dry_run {
                    GuildOutcome::Checked
                } else {
                    GuildOutcome::Imported
                };
                report.guilds.insert(name, outcome);
            }
            Err(e) => {
                tracing::warn!(quack.guild_id = %name, error = %e, "server not imported");
                match e {
                    ImportError::Server(problems) => {
                        for p in problems {
                            report.problem(&name, p);
                        }
                    }
                    other => report.problem(&name, other.to_string()),
                }
                report.guilds.insert(name, GuildOutcome::Failed);
            }
        }
    }
}
