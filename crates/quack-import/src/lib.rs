//! One-time import from Quack's old MySQL database into PostgreSQL
//! (design §19).
//!
//! [`run`] inspects the source (ledger and columns against the
//! [manifest](source::manifest)), digests every table into a fingerprint,
//! then imports each server in its own PostgreSQL transaction together with
//! its `import_guilds` row, and returns a [`Report`]. A rerun skips servers
//! already imported from the same fingerprint and refuses one imported from
//! different data. `--dry-run` writes every server inside a transaction that
//! is rolled back, so every constraint and check runs for real, and keeps
//! only its `import_runs` row.
//!
//! The only crate with sqlx's `mysql` driver. Its queries are checked at
//! runtime, so it builds without either database.
//!
//! The end-to-end tests (`tests/import.rs`) load the Go schema and the
//! fixtures in `tests/fixtures` (generated by `gen_fixture.py`) into a
//! scratch MySQL 8.4 and import them into a fresh PostgreSQL 18. They run
//! when `QUACK_IMPORT_TEST_MYSQL_URL` and `QUACK_IMPORT_TEST_PG_URL` name
//! servers the tests may create and drop databases on, and skip otherwise;
//! CI sets both (MySQL 8.4 and PostgreSQL 18 service containers).

